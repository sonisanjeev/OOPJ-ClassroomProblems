package Problem5;

public class Calculator {

    // (a) add(int, int)
    void add(int a, int b) {
        System.out.println("Addition: " + (a + b));
    }

    // (b) add(double, double)
    void add(double a, double b) {
        System.out.println("Addition: " + (a + b));
    }

    // (c) add(int, int, int)
    void add(int a, int b, int c) {
        System.out.println("Addition: " + (a + b + c));
    }
}